import { test, describe } from "node:test";
import assert from "node:assert/strict";

import { extractClaims, parseCitations, parseRegistry, checkReportMarkdown, renderReportShell } from "../dist/report.js";

const SOURCES = [
  { url: "https://www.nhtsa.gov/a", score: 90, grade: "A", publishedAt: "2026-10-01", flags: [], scoredAt: "2026-10-21T00:00:00Z" },
  { url: "https://example.com/b", score: 50, grade: "C", publishedAt: null, flags: ["no-date", "paywall"], scoredAt: "2026-10-21T00:00:00Z" },
];

const shell = () => renderReportShell("Test topic", SOURCES, new Date("2026-10-21T00:00:00Z"));
const withClaims = (...claims) => shell().replace("\n## Citation registry\n", `\n${claims.join("\n")}\n\n## Citation registry\n`);

describe("parseCitations", () => {
  test("accepts single, adjacent and comma/semicolon-separated citations", () => {
    assert.deepEqual(parseCitations("a [S1] b"), ["S1"]);
    assert.deepEqual(parseCitations("a [S1][S2]"), ["S1", "S2"]);
    assert.deepEqual(parseCitations("a [S1, S3; S12]"), ["S1", "S3", "S12"]);
    assert.deepEqual(parseCitations("a [s2] and [S2]"), ["S2"]);
    assert.deepEqual(parseCitations("no citations [1] [Sx]"), []);
  });
});

describe("renderReportShell", () => {
  test("numbers sources and records score, grade, date and flags", () => {
    const md = shell();
    assert.match(md, /^# Research report — Test topic/);
    assert.match(md, /_Generated by research-scope-mcp \d+\.\d+\.\d+ on 2026-10-21\._/);
    assert.match(md, /\[S1\] https:\/\/www\.nhtsa\.gov\/a — score 90\/100 \(A, published 2026-10-01\)/);
    assert.match(md, /\[S2\] https:\/\/example\.com\/b — score 50\/100 \(C, no date\)/);
    assert.match(md, /### \[S2\] flags\nno-date, paywall/);
    assert.match(md, /### \[S1\] flags\nnone/);
  });
});

describe("extractClaims", () => {
  test("a fresh shell has no claims (template preamble and example comments are skipped)", () => {
    assert.deepEqual(extractClaims(shell()), []);
  });

  test("ignores the citation registry and scoring appendix, including ### subsections", () => {
    const md = `## Citation registry\n[S1] https://example.com/a-very-long-url-that-is-over-forty-chars — score 1\n## Scoring appendix\n### [S1] flags\nconflict-of-interest:sponsored, no-date, paywall, thin-content`;
    assert.deepEqual(extractClaims(md), []);
  });

  test("counts claims in sections that come after the appendix", () => {
    const md = `${shell()}\n## Conclusion\n\nThe evidence overall supports the vendor's narrower claim about tiers.`;
    const claims = extractClaims(md);
    assert.equal(claims.length, 1);
    assert.match(claims[0].claim, /^The evidence overall/);
  });

  test("strips list markers, numbering and blockquotes; ignores short lines and code fences", () => {
    const md = [
      "- Bulleted claim that is long enough to count as a finding [S1]",
      "2. Numbered claim that is long enough to count as a finding [S1]",
      "> Quoted claim that is long enough to count as a finding [S1]",
      "Too short [S1]",
      "```",
      "code block line that is long enough to count but is code",
      "```",
    ].join("\n");
    const claims = extractClaims(md);
    assert.deepEqual(
      claims.map((c) => c.claim),
      [
        "Bulleted claim that is long enough to count as a finding",
        "Numbered claim that is long enough to count as a finding",
        "Quoted claim that is long enough to count as a finding",
      ]
    );
    assert.deepEqual(claims.map((c) => c.claimId), ["C1", "C2", "C3"]);
  });

  test("skips multi-line HTML comments but keeps text after an inline comment", () => {
    const md = [
      "<!--",
      "A commented-out paragraph that would otherwise be counted as a claim.",
      "-->",
      "Visible claim that is long enough to be checked by the tool <!-- note --> [S1]",
    ].join("\n");
    const claims = extractClaims(md);
    assert.equal(claims.length, 1);
    assert.equal(claims[0].claimId, "C4");
    assert.deepEqual(claims[0].sourceUrls, ["S1"]);
  });

  test("handles CRLF line endings", () => {
    assert.equal(extractClaims("Line one is a claim long enough to be counted [S1]\r\n\r\n").length, 1);
  });
});

describe("parseRegistry", () => {
  test("reads [Sn] entries from the registry section only", () => {
    const reg = parseRegistry(shell() + "\n## Notes\n[S9] https://not-in-registry.example\n");
    assert.deepEqual([...reg.entries()], [
      ["S1", "https://www.nhtsa.gov/a"],
      ["S2", "https://example.com/b"],
    ]);
  });
});

describe("checkReportMarkdown", () => {
  test("a fresh shell fails with a 'no claims' verdict", () => {
    const r = checkReportMarkdown(shell());
    assert.equal(r.pass, false);
    assert.equal(r.claimsFound, 0);
    assert.match(r.verdict, /no claims found/);
  });

  test("passes when every claim cites a registered source", () => {
    const r = checkReportMarkdown(withClaims("- The regulator confirmed the rule takes effect in 2027 [S1].", "- An independent analysis disputes the cost estimate [S1, S2]."));
    assert.equal(r.pass, true, r.verdict);
    assert.equal(r.claimsFound, 2);
    assert.equal(r.claimsCited, 2);
    assert.equal(r.registrySources, 2);
    assert.equal(r.orphanClaims, "none");
    assert.equal(r.unknownCitations, "none");
    assert.match(r.verdict, /^PASS/);
  });

  test("orphan claims fail and are listed", () => {
    const r = checkReportMarkdown(withClaims("- The regulator confirmed the rule takes effect in 2027 [S1].", "- Retention varies far more between plans than marketing concedes."));
    assert.equal(r.pass, false);
    assert.equal(r.claimsCited, 1);
    assert.equal(r.orphanClaims.length, 1);
    assert.match(r.orphanClaims[0].claim, /^Retention varies/);
    assert.match(r.verdict, /1 orphan claim/);
  });

  test("citing an id missing from the registry fails (regression: [S99] used to pass)", () => {
    const r = checkReportMarkdown(withClaims("- This claim cites a source that was never scored at all [S99]."));
    assert.equal(r.pass, false);
    assert.equal(r.orphanClaims.length, 1, "a claim whose only citation is unknown is an orphan");
    assert.deepEqual(r.unknownCitations, [{ claimId: r.orphanClaims[0].claimId, citations: ["S99"] }]);
    assert.match(r.verdict, /missing from the citation registry/);
  });

  test("a claim with one valid and one unknown citation is cited but still fails", () => {
    const r = checkReportMarkdown(withClaims("- Mixed citations: one real source and one typo here [S1][S7]."));
    assert.equal(r.pass, false);
    assert.equal(r.claimsCited, 1);
    assert.equal(r.orphanClaims, "none");
    assert.deepEqual(r.unknownCitations[0].citations, ["S7"]);
  });

  test("a report without a registry cannot pass", () => {
    const r = checkReportMarkdown("# Notes\n\nA claim that cites a source but there is no registry [S1].");
    assert.equal(r.pass, false);
    assert.match(r.verdict, /no citation registry/);
  });
});
