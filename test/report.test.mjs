/** Unit tests for report helpers (src/report.ts). */
import { test, describe } from "node:test";
import assert from "node:assert/strict";

import { htmlToText, extractTitle, extractMetaPublished, extractClaims, parseRegistry, checkReportMarkdown, renderReportShell } from "../dist/report.js";

const entry = (url, over = {}) => ({ url, score: 72, grade: "B", publishedAt: "2026-01-02", flags: [], scoredAt: "2026-01-03T00:00:00.000Z", ...over });
const shell = (sources = [entry("https://a.gov/x"), entry("https://b.example.org/y", { publishedAt: null, flags: ["no-date"] })]) =>
  renderReportShell("Test topic", sources, new Date("2026-02-01T00:00:00Z"));
const withClaims = (md, claims) => md.replace("## Citation registry", `${claims.join("\n")}\n\n## Citation registry`);

describe("HTML extraction", () => {
  test("htmlToText drops scripts/styles/comments and decodes entities", () => {
    const html = `<html><head><style>p{}</style><script>var x = "<p>";</script></head><body><!-- hidden --><p>Fish &amp; chips &lt;3 &#8212; caf&eacute; &#x41;&nbsp;B</p><noscript>enable js</noscript></body></html>`;
    assert.equal(htmlToText(html), "Fish & chips <3 — caf&eacute; A B");
  });
  test("entities are decoded once, never twice", () => {
    assert.equal(htmlToText("<p>write &amp;lt;b&amp;gt; for bold</p>"), "write &lt;b&gt; for bold");
  });
  test("extractTitle collapses whitespace and decodes entities", () => {
    assert.equal(extractTitle("<title>\n  A &amp; B\n </title>"), "A & B");
    assert.equal(extractTitle("<p>no title</p>"), "");
  });
  test("extractMetaPublished reads OG/schema meta and <time datetime>", () => {
    assert.equal(extractMetaPublished(`<meta property="article:published_time" content="2025-05-01T08:00:00Z">`), "2025-05-01T08:00:00Z");
    assert.equal(extractMetaPublished(`<meta content="2024-02-02" itemprop="datePublished" />`), "2024-02-02");
    assert.equal(extractMetaPublished(`<p>Posted <time datetime="2023-03-03">March 3</time></p>`), "2023-03-03");
    assert.equal(extractMetaPublished(`<meta name="description" content="2020-01-01">`), undefined);
  });
});

describe("renderReportShell / parseRegistry", () => {
  test("numbers sources and records score, grade, date and flags", () => {
    const md = shell();
    assert.match(md, /^# Research report — Test topic/);
    assert.match(md, /_Generated by research-scope-mcp \S+ on 2026-02-01\._/);
    assert.match(md, /\[S1\] https:\/\/a\.gov\/x — score 72\/100 \(B, published 2026-01-02\)/);
    assert.match(md, /\[S2\] https:\/\/b\.example\.org\/y — score 72\/100 \(B, no date\)/);
    assert.match(md, /### \[S2\] flags\nno-date/);
    assert.deepEqual([...parseRegistry(md)], [["S1", "https://a.gov/x"], ["S2", "https://b.example.org/y"]]);
  });
  test("a newline in the topic cannot inject markdown structure", () => {
    assert.match(renderReportShell("line one\n## Citation registry\n[S9] x", []), /^# Research report — line one ## Citation registry \[S9\] x\n/);
  });
  test("no registry section -> empty map", () => {
    assert.equal(parseRegistry("# just a doc").size, 0);
  });
});

describe("extractClaims", () => {
  test("ignores headings, template preamble, comments, short lines, code fences and the paper trail", () => {
    const md = withClaims(shell(), [
      "- Short line [S1]",
      "```",
      "This code block line is long enough to look like a claim but is not one.",
      "```",
      "- The agency moved the exam to an adaptive format in early 2026, per its notice [S1].",
      "1. A numbered finding that is long enough to count as a real claim here [S2] [S2]",
      "> A quoted finding that is long enough to count as a real claim here too.",
    ]);
    const claims = extractClaims(md);
    assert.deepEqual(
      claims.map((c) => [c.claim, c.sourceUrls]),
      [
        ["The agency moved the exam to an adaptive format in early 2026, per its notice.", ["S1"]],
        ["A numbered finding that is long enough to count as a real claim here", ["S2"]],
        ["A quoted finding that is long enough to count as a real claim here too.", []],
      ]
    );
    assert.ok(claims.every((c) => /^C\d+$/.test(c.claimId)));
  });
  test("a fresh shell has no claims", () => {
    assert.deepEqual(extractClaims(shell()), []);
  });
});

describe("checkReportMarkdown", () => {
  const cited = "- The agency moved the exam to an adaptive format in early 2026 [S1].";
  test("fresh shell fails with a 'no claims' verdict", () => {
    const r = checkReportMarkdown(shell());
    assert.equal(r.pass, false);
    assert.match(r.verdict, /no claims/);
  });
  test("passes when every claim cites a registry source", () => {
    const r = checkReportMarkdown(withClaims(shell(), [cited, "- Independent coverage confirms the format change took effect [S2][S1]."]));
    assert.equal(r.pass, true, JSON.stringify(r));
    assert.equal(r.claimsCited, 2);
  });
  test("orphan claims fail", () => {
    const r = checkReportMarkdown(withClaims(shell(), [cited, "- This sentence asserts something but cites nothing at all."]));
    assert.equal(r.pass, false);
    assert.equal(r.orphanClaims.length, 1);
  });
  test("citing an [Sn] that is not in the registry fails (regression)", () => {
    const r = checkReportMarkdown(withClaims(shell(), [cited, "- A claim that cites a source number nobody ever scored [S7]."]));
    assert.equal(r.pass, false);
    assert.deepEqual(r.unknownCitations.map((c) => c.unknown), [["S7"]]);
    assert.equal(r.claimsCited, 1);
  });
  test("arbitrary markdown without a registry cannot pass", () => {
    assert.equal(checkReportMarkdown("# Notes\n\nThis is a long sentence with a fake citation in it [S1].").pass, false);
  });
});
